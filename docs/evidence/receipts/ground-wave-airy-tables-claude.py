#!/usr/bin/env python3
"""claude, TOOL_ONLY: extracts the numeric tables of NTIA/ITS LFMF v1.1 (public domain, 15 U.S.C. 105) for the
Python port oracle/ground_wave_oracle.py, so that no constant is retyped by hand.

Reads src/Airy.cpp and src/WiRoot.cpp of the unmodified LFMF source tree (GitHub main.zip, sha256
be6ed041d4f095c8845e8cce800e1a4ffb568401dec6f5d93c14b7a8ce58fd95) and prints Python literals for NQTT, ASV, AV, APV
(the Ai / Ai' centres of expansion; the Bi tables are not used by LFMF and are not extracted), AKP and AK.
Each literal keeps the decimal text of the source, so Python parses the same binary64 values as the C++ compiler.
Usage: python -I ground-wave-airy-tables-claude.py <LFMF-main dir>            (prints the literals)
       python -I ground-wave-airy-tables-claude.py <LFMF-main dir> --check <oracle .py>   (exit 1 on mismatch)"""
import hashlib
import re
import sys
from pathlib import Path

NUM = r"[-+]?\d+\.\d+(?:[eE][-+]?\d+)?"


def block(text, name):
    """Body of the array declaration `name[...]... = { ... };` (comments in the body removed)."""
    m = re.search(r"\b" + name + r"\s*\[[^\]]*\](?:\s*\[[^\]]*\])*\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit(f"table {name} not found")
    return re.sub(r"//[^\n]*", "", m.group(1))


def complex_table(text, name):
    pairs = re.findall(r"\{\s*(" + NUM + r")\s*,\s*(" + NUM + r")\s*\}", block(text, name))
    return [f"complex({a}, {b})" for a, b in pairs]


def render(src):
    airy = (src / "src" / "Airy.cpp").read_text(encoding="utf-8")
    root = (src / "src" / "WiRoot.cpp").read_text(encoding="utf-8")
    nqtt = re.findall(r"\d+", block(airy, "NQTT"))
    asv = re.findall(r"\{\s*(" + NUM + r")\s*,\s*(" + NUM + r")\s*\}", block(airy, "ASV"))
    av, apv = complex_table(airy, "AV"), complex_table(airy, "APV")
    akp = re.findall(NUM, block(root, "akp"))
    ak = re.findall(NUM, block(root, "ak"))
    # 70 centres of expansion: Airy() refuses N >= 70 (index N - 1 into AV/APV)
    if (len(nqtt), len(asv), len(av), len(apv), len(akp), len(ak)) != (15, 15, 70, 70, 11, 11):
        raise SystemExit("unexpected table sizes")
    lines = ["# --- generated by docs/evidence/receipts/ground-wave-airy-tables-claude.py from LFMF v1.1 ---",
             "NQTT = (" + ", ".join(nqtt) + ")",
             "ASV = (" + ", ".join(f"({a}, {b})" for a, b in asv) + ")"]
    for name, rows in (("AV", av), ("APV", apv)):
        lines.append(f"{name} = (")
        lines += [f"    {r}," for r in rows]
        lines.append(")")
    lines.append("AKP = (" + ", ".join(akp) + ")")
    lines.append("AK = (" + ", ".join(ak) + ")")
    lines.append("# --- end of generated tables ---")
    return "\n".join(lines) + "\n"


def main(argv):
    src = Path(argv[0])
    text = render(src)
    if len(argv) == 3 and argv[1] == "--check":
        oracle = Path(argv[2]).read_text(encoding="utf-8")
        if text not in oracle:
            print("AIRY_TABLES_MISMATCH")
            return 1
        print(f"AIRY_TABLES_MATCH sha256 {hashlib.sha256(text.encode()).hexdigest()}")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
