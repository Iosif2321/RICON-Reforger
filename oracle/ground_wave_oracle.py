def airy_w1(z, derivative):
    """Airy(Z, WONE или DWONE, WAIT) из Airy.cpp: функция Эйри третьего рода w1 Wait (= Wi(2) Hufford) или её
    производная. Сдвинутый ряд Тейлора вокруг табличных центров либо асимптотический ряд (DLMF 9.7)."""
    U = complex(math.cos(-2.0 * PI / 3.0), math.sin(-2.0 * PI / 3.0))
    ZU = z * U
    reflection = False
    if ZU.imag <= 0:
        reflection = True
        ZU = complex(ZU.real, -ZU.imag)
    A = [complex(0.0, 0.0), complex(0.0, 0.0)]
    index = 1 if derivative else 0
    N = 0
    NQ8 = 0
    if ZU.real >= -6.5 and ZU.real <= 7.5 and ZU.imag <= 6.35:
        real_idx = int(ZU.real + math.copysign(0.5, ZU.real))
        imag_idx = int(math.sin(PI / 3.0) * (ZU.imag + 0.5))
        if not (0 <= real_idx + 6 and real_idx + 7 < len(NQTT)):
            raise NumericFailure("центр разложения вне таблицы NQTT")
        N = NQTT[real_idx + 6] + imag_idx
        if N >= 70:
            raise NumericFailure("индекс центра разложения вне таблицы Ai")
        NQ8 = NQTT[real_idx + 7]
        if N < NQ8:
            coe = complex(float(real_idx), float(imag_idx) / math.sin(PI / 3.0))
            ZU = ZU - coe
            ai, aip = AV[N - 1], APV[N - 1]
            B1 = ai
            B3 = B1 * coe * ZU
            A[1] = aip
            B2 = A[1] * ZU
            A[0] = B2 + B1
            A[1] = A[1] + B3
            AN = 1.0
            count = 0
            while True:
                while True:
                    AN = AN + 1.0
                    B3 = B3 * ZU / AN
                    A[0] = B3 + A[0]
                    B0, B1, B2 = B1, B2, B3
                    B3 = (coe * B1 + ZU * B0) * ZU / AN
                    A[1] = B3 + A[1]
                    if not (abs(B2) > 0.5E-7 * abs(A[0]) or abs(B3) > 0.5E-7 * abs(A[1])):
                        break
                count += 1
                if count >= 3:
                    break
    if ZU.real < -6.5 or ZU.real > 7.5 or ZU.imag > 6.35 or N >= NQ8 or (z.real == 0.0 and z.imag == 0.0):
        if ZU == 0:
            raise NumericFailure("асимптотический ряд в нуле")
        ZA = cmath.sqrt(ZU)
        ZT = (2.0 / 3.0) * ZU * ZA
        one = -1.0
        sum1 = complex(0.0, 0.0)
        for i in range(14):
            sum1 = _cdiv(math.pow(one, i) * ASV[i][index] + sum1, ZT)
        sum1 = ASV[14][index] + sum1
        sum2 = complex(0.0, 0.0)
        if abs(cmath.phase(ZU)) > PI / 3.0:
            for i in range(14):
                sum2 = _cdiv(ASV[i][index] + sum2, ZT)
            sum2 = ASV[14][index] + sum2
        ZB = -1.0 * cmath.sqrt(ZA) if derivative else _cdiv(1.0, cmath.sqrt(ZA))
        e = _cexp(ZT)
        ZB1 = _cdiv(ZB * 1.0, 2.0 * e * math.sqrt(PI))
        ZB2 = ZB * e / (2.0 * math.sqrt(PI))
        if derivative:
            A[index] = ZB1 * sum1 - complex(0.0, 1.0) * ZB2 * sum2
        else:
            A[index] = ZB1 * sum1 + complex(0.0, 1.0) * ZB2 * sum2
    ai = A[index]
    if reflection:
        ai = complex(ai.real, -ai.imag)
    if derivative:
        U = complex(-1.0 * math.sqrt(3.0 * PI), -1.0 * math.sqrt(PI))
    else:
        U = complex(math.sqrt(3.0 * PI), -1.0 * math.sqrt(PI))
    return ai * U


def wi_root(i, q):
    """WiRoot(i, …, q, …, WONE, WAIT): i-й корень w1'(t) − q·w1(t) = 0 методом Ньютона от вещественного корня Ai/Ai'."""
    ph = complex(math.cos(2.0 * PI / 3.0), math.sin(2.0 * PI / 3.0))
    if math.pow(abs(q), 3.0) <= 4 * (i - 1) + 3:
        if i <= 10:
            tt = AKP[i - 1]
        else:
            t = (3.0 / 8.0) * PI * (4.0 * (i - 1) + 1)
            tt = -1.0 * math.pow(t, 2.0 / 3.0) * (1.0 - ((7.0 / 48.0) * math.pow(t, -2.0))
                                                   + ((35.0 / 288.0) * math.pow(t, -4.0)))
        ti = tt * ph
        ti = ti + _cdiv(q, ti)
    else:
        if i <= 10:
            tt = AK[i - 1]
        else:
            t = (3.0 / 8.0) * PI * (4.0 * (i - 1) + 3.0)
            tt = -1.0 * math.pow(t, 2.0 / 3.0) * (1.0 + ((5.0 / 48.0) * math.pow(t, -2.0))
                                                   - ((5.0 / 36.0) * math.pow(t, -4.0)))
        ti = tt * ph
        ti = ti + _cdiv(1.0, q)
    count = 0
    eps = 0.5e-6
    while True:
        wi = airy_w1(ti, False)
        dwi = airy_w1(ti, True)
        step = _cdiv(dwi - q * wi, ti * wi - q * dwi)
        ti = ti - step
        count += 1
        ratio = _cdiv(step, ti)
        if not (count <= 25 and abs(ratio.real) + abs(ratio.imag) > eps):
            break
    if count == 26:
        raise NumericFailure("корень не сошёлся за 25 итераций Ньютона")
    return ti


def residue_series(k, h_1_km, h_2_km, nu, theta_rad, q):
    """ResidueSeries.cpp: ряд вычетов (NTIA 99-368 ур. 26) для больших расстояний; нормированное поле."""
    gw = complex(0.0, 0.0)
    y_high = k * h_2_km / nu
    y_low = k * h_1_km / nu
    x = nu * theta_rad
    for i in range(200):
        t = wi_root(i + 1, q)
        w1 = airy_w1(t, False)
        if h_1_km > 0:
            w = _cdiv(airy_w1(t - y_low, False), w1)
            if h_2_km > 0:
                w *= _cdiv(airy_w1(t - y_high, False), w1)
        elif h_2_km > 0:
            w = _cdiv(airy_w1(t - y_high, False), w1)
        else:
            w = complex(1, 0)
        w = _cdiv(w, t - (q * q))
        g = w * _cexp(-1.0 * J * x * t)
        gw += g
        if i != 0:
            square = gw * gw
            if abs(square.real) + abs(square.imag) == 0.0:
                return 0.0
            ratio = _cdiv(g, gw)
            if abs(ratio.real) + abs(ratio.imag) < 0.0005:
                break
    ew = math.sqrt(x) * complex(math.sqrt(PI / 2), -math.sqrt(PI / 2)) * gw
    return abs(ew)


def flat_earth_curve_correction(delta, q, h_1_km, h_2_km, d_km, k, a_e_km):
    """FlatEarthCurveCorrection.cpp: плоская Земля с поправкой на кривизну (NTIA 99-368 ур. 28–36)."""
    qi = (-0.5 + J * 0.5) * math.sqrt(k * d_km) * delta
    p = qi * qi
    p2 = p ** 2
    q3 = q ** 3
    q6 = q ** 6
    q9 = q ** 9
    if abs(q) > 0.1:
        fofp = 1.0 + math.sqrt(PI) * J * qi * wofz(qi)
        fofx = fofp + _cdiv(1.0 - J * cmath.sqrt(PI * p) - (1.0 + 2.0 * p) * fofp, 4.0 * q3)
        fofx = fofx + _cdiv(1.0 - J * cmath.sqrt(PI * p) * (1.0 - p) - 2.0 * p + 5.0 * p2 / 6.0
                            + (p2 / 2.0 - 1.0) * fofp, 4.0 * q6)
    else:
        a = [complex(1.0, 0.0),
             -J * math.sqrt(PI),
             complex(-2.0, 0.0),
             J * math.sqrt(PI) * (1.0 + _cdiv(1.0, 4.0 * q3)),
             4.0 / 3.0 * (1.0 + _cdiv(1.0, 2.0 * q3)),
             -J * math.sqrt(PI) / 4.0 * (1.0 + _cdiv(3.0, 4.0 * q3)),
             -8.0 / 15.0 * (1.0 + _cdiv(1.0, q3) + _cdiv(7.0, 32.0 * q6)),
             J * math.sqrt(PI) / 6.0 * (1.0 + _cdiv(5.0, 4.0 * q3) + _cdiv(27.0, 32.0 * q6)),
             16.0 / 105.0 * (1.0 + _cdiv(3.0, 2.0 * q3) + _cdiv(27.0, 32.0 * q6)),
             -J * math.sqrt(PI) / 24.0 * (1.0 + _cdiv(7.0, 4.0 * q3) + _cdiv(5.0, 4.0 * q6) + _cdiv(21.0, 64.0 * q9))]
        x = d_km / a_e_km * math.pow(k * a_e_km / 2.0, (1.0 / 3.0))
        fofx = complex(0.0, 0.0)
        base = cmath.exp(J * PI / 4.0) * q * math.pow(x, 1.0 / 2.0)
        for ii in range(10):
            fofx = fofx + a[ii] * base ** ii
    return abs(fofx * (1.0 + J * k * h_2_km * delta) * (1.0 + J * k * h_1_km * delta))


def validate(h_tx_m, h_rx_m, f_mhz, p_tx_w, n_s, d_km, epsilon, sigma, pol):
    """ValidateInputs.cpp (порядок проверок сохранён)."""
    if h_tx_m < 0 or h_tx_m > 50:
        return ERROR_TX_TERMINAL_HEIGHT
    if h_rx_m < 0 or h_rx_m > 50:
        return ERROR_RX_TERMINAL_HEIGHT
    if f_mhz < 0.01 or f_mhz > 30:
        return ERROR_FREQUENCY
    if p_tx_w <= 0:
        return ERROR_TX_POWER
    if n_s < 250 or n_s > 400:
        return ERROR_SURFACE_REFRACTIVITY
    if d_km < 0.001 or d_km > 10000:
        return ERROR_PATH_DISTANCE
    if epsilon < 1:
        return ERROR_EPSILON
    if sigma <= 0:
        return ERROR_SIGMA
    if pol not in (0, 1):
        return ERROR_POLARIZATION
    return SUCCESS


def lfmf(h_tx_m, h_rx_m, f_mhz, p_tx_w, n_s, d_km, epsilon, sigma, pol):
    """LFMF_CPP: возвращает (rc, A_btl дБ, E дБ(мкВ/м), P_rx дБм, метод). pol: 0 — H, 1 — V.
    NumericFailure — там, где C++ прервался бы исключением или вернул ±inf (изменение 3 в шапке)."""
    rc = validate(h_tx_m, h_rx_m, f_mhz, p_tx_w, n_s, d_km, epsilon, sigma, pol)
    if rc != SUCCESS:
        return rc, None, None, None, None
    f_hz = f_mhz * 1e6
    lambda_m = C / f_hz
    h_1_km = min(h_tx_m, h_rx_m) / 1000
    h_2_km = max(h_tx_m, h_rx_m) / 1000
    a_e_km = A_0_KM * 1 / (1 - 0.04665 * math.exp(0.005577 * n_s))
    theta_rad = d_km / a_e_km
    k = 2.0 * PI * 1000 / lambda_m
    nu = math.cbrt(a_e_km * k / 2.0)
    eta = complex(epsilon, -sigma / (EPSILON_0 * 2 * PI * f_hz))
    delta = cmath.sqrt(eta - 1.0)
    if pol == 1:
        delta = delta / eta
    q = -nu * J * delta
    d_test_km = 80 / math.cbrt(f_mhz)
    if d_km < d_test_km:
        e_gw = flat_earth_curve_correction(delta, q, h_1_km, h_2_km, d_km, k, a_e_km)
        method = FLAT_EARTH_CURVE
    else:
        e_gw = residue_series(k, h_1_km, h_2_km, nu, theta_rad, q)
        method = RESIDUE_SERIES
    g_tx = math.pow(10, G_DBI / 10)
    e_0 = math.sqrt(ETA * (p_tx_w * g_tx) / (4.0 * PI)) / d_km
    e_gw = e_gw * e_0
    if not math.isfinite(e_gw) or e_gw <= 0:
        raise NumericFailure("нулевое или не конечное поле")
    a_btl = (10 * math.log10(p_tx_w * g_tx) + 10 * math.log10(ETA * 4 * PI) + 20 * math.log10(f_hz)
             - 20 * math.log10(e_gw / 1000) - 20 * math.log10(C))
    e_dbuvm = 60 + 20 * math.log10(e_gw)
    p_rx_dbm = e_dbuvm + G_DBI - 20.0 * math.log10(f_hz) + 42.8
    return SUCCESS, a_btl, e_dbuvm, p_rx_dbm, method


