def _number(value):
    if type(value) not in (int, float):
        raise ValueError("ожидалось число")
    try:
        value = float(value)
    except OverflowError:
        raise ValueError("целое JSON вне binary64 (codex #4118)") from None
    if not math.isfinite(value):
        raise ValueError("не конечное число")
    return value


def evaluate(raw):
    """GW02–GW05. Вход не изменяется; результат создаётся заново."""
    try:
        if type(raw) is not dict or set(raw) != INPUT_FIELDS:
            raise ValueError("поля входа")
        ground = raw["ground"]
        if type(ground) is not dict or set(ground) != GROUND_FIELDS:
            raise ValueError("поля ground")
        f = _number(raw["frequencyMHz"])
        d = _number(raw["distanceKm"])
        h_tx = _number(raw["txHeightM"])
        h_rx = _number(raw["rxHeightM"])
        n_s = _number(raw["surfaceRefractivityN"])
        eps = _number(ground["epsilonReal"])
        sigma = _number(ground["conductivitySm"])
        pol, provenance = raw["polarization"], ground["provenance"]
        if type(pol) is not str or pol not in ("V", "H"):
            raise ValueError("поляризация")
        if type(provenance) is not str or provenance not in PROVENANCE:
            raise ValueError("provenance")
        if f <= 0 or d <= 0 or h_tx < 0 or h_rx < 0 or n_s < 0 or eps < 1 or sigma < 0:
            raise ValueError("физически недопустимое значение")
    except (ValueError, TypeError, KeyError):
        return {"code": "INVALID_INPUT"}
    if (h_tx > 50 or h_rx > 50 or not 0.01 <= f <= 30 or not 250 <= n_s <= 400 or not 0.001 <= d <= 10000
            or sigma == 0 or pol == "H"):
        return {"code": "OUT_OF_MODEL_DOMAIN"}
    try:
        rc, a_btl, e_dbuvm, _p_rx, method = lfmf(h_tx, h_rx, f, REFERENCE_POWER_W, n_s, d, eps, sigma, 1)
    except (NumericFailure, ArithmeticError, ValueError):
        # Конечные, но крайние ε′/σ (codex #4088): LFMF даёт ±inf/NaN или прерывается исключением C++
        # (receipts/ground-wave-extremes-claude.py: 576 случаев, граница отказа совпала полностью).
        return {"code": "NUMERIC_FAILURE"}
    if rc != SUCCESS:  # GW03 повторяет ValidateInputs; сюда попасть нельзя
        raise AssertionError(f"LFMF rc {rc} после проверок GW03")
    wavelength_m = C / (f * 1e6)
    return {"code": "OK", "basicLossDb": a_btl, "fieldDbuVm": e_dbuvm, "method": METHODS[method],
            "kr": 2 * PI * (d * 1000) / wavelength_m, "heightToWavelength": max(h_tx, h_rx) / wavelength_m,
            "provenance": provenance}


def _unique_pairs(pairs):
    result = {}
    for name, value in pairs:
        if name in result:
            raise ValueError("повтор ключа JSON: " + name)
        result[name] = value
    return result


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"), object_pairs_hook=_unique_pairs)


def lf_sha(path):
    return hashlib.sha256(Path(path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def check(path):
    """Сверка корпуса: коды/метод/provenance точно, дБ abs ≤ 1e-8, kr и h/λ rel ≤ 1e-12, инвариант GW05,
    опубликованные примеры NTIA ≤ 0.05 дБ через lfmf()."""
    data = read_json(path)
    if (type(data) is not dict or set(data) != {"schema", "version", "revision", "source", "requirementsLfSha256",
                                                 "note", "cases", "ntiaExamples"}
            or data["schema"] != "ricon.oracle.ground_wave" or data["version"] != 1 or type(data["revision"]) is not int
            or data["source"] != "docs/req/REQ-ground-wave.md" or data["requirementsLfSha256"] != lf_sha(REQ)):
        raise ValueError("неверная схема корпуса или SHA REQ")
    errors, ids = [], set()
    for case in data["cases"]:
        if set(case) != {"id", "note", "jsonOnly", "provenance", "input", "expect"} or case["id"] in ids:
            raise ValueError("неверный случай корпуса")
        ids.add(case["id"])
        cid, want = case["id"], case["expect"]
        got = evaluate(case["input"])
        if got["code"] != want.get("code"):
            errors.append(f"{cid}: code {got['code']} != {want.get('code')}")
            continue
        if want["code"] != "OK":
            if set(want) != {"code"}:
                errors.append(f"{cid}: лишние поля отказа")
            continue
        if set(want) != set(OUTPUT_FIELDS):
            errors.append(f"{cid}: поля выхода")
            continue
        for name in ("method", "provenance"):
            if got[name] != want[name]:
                errors.append(f"{cid}: {name}")
        for name in ("basicLossDb", "fieldDbuVm"):
            if not abs(got[name] - want[name]) <= 1e-8:
                errors.append(f"{cid}: {name} {got[name]!r} != {want[name]!r}")
        for name in ("kr", "heightToWavelength"):
            if not math.isclose(got[name], want[name], rel_tol=1e-12, abs_tol=0):
                errors.append(f"{cid}: {name}")
        invariant = want["basicLossDb"] + want["fieldDbuVm"] - 20 * math.log10(case["input"]["frequencyMHz"])
        if not abs(invariant - LFMF_CONSTANT_DB) <= 1e-9:
            errors.append(f"{cid}: инвариант GW05 {invariant!r}")
    for row in data["ntiaExamples"]:
        args = [row[k] for k in ("hTxM", "hRxM", "fMHz", "pTxW", "nS", "dKm", "epsilon", "sigma", "pol")]
        rc, a, e, p, m = lfmf(*args)
        if rc != row["rc"] or (rc == 0 and (m != row["method"] or abs(a - row["aBtlDb"]) > 0.05
                                            or abs(e - row["eDbuVm"]) > 0.05 or abs(p - row["pRxDbm"]) > 0.05)):
            errors.append(f"NTIA строка {row['row']}: {rc} {a} {e} {p} {m}")
    for error in errors:
        print(error)
    print(f"{'PASS' if not errors else 'FAIL'}: {len(data['cases'])} случаев GW, {len(data['ntiaExamples'])} примеров NTIA")
    return int(bool(errors))


