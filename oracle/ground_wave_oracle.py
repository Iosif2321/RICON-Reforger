PROVENANCE = ("SOURCE_DOMAIN", "ASSUMED_CONFIG", "TEST_ONLY")
CODES = ("INVALID_INPUT", "OUT_OF_MODEL_DOMAIN", "NUMERIC_FAILURE", "OK")
METHODS = ("FLAT_EARTH_CURVE", "RESIDUE_SERIES")
INPUT_FIELDS = {"frequencyMHz", "distanceKm", "txHeightM", "rxHeightM", "polarization", "surfaceRefractivityN", "ground"}
GROUND_FIELDS = {"epsilonReal", "conductivitySm", "provenance"}
REFERENCE_POWER_W = 1000.0  # P.368 Annex 1: 1 кВт, 300 мВ/м на 1 км
OUTPUT_FIELDS = ("code", "basicLossDb", "fieldDbuVm", "method", "kr", "heightToWavelength", "provenance")
