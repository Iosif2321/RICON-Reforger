# TOOL_ONLY N0 fixed neutral generator. No game/input/audio/network/child process.
[CmdletBinding()]
param([switch]$EnableN0, [string]$RunId, [string]$RunDir, [string]$OwnerToken, [string]$Scenario)
if (-not $EnableN0) { Write-Output 'N0_DISABLED'; return }
Set-StrictMode -Version 2.0
$ErrorActionPreference='Stop'
if ($RunId -cnotmatch '^[0-9a-f]{32}$' -or $OwnerToken -cnotmatch '^[0-9a-f]{32}$' -or
    $Scenario -cnotin @('Normal','DelayEmit','Hanging')) { throw 'N0_BAD_ARGUMENTS' }
if ($env:OS -ne 'Windows_NT' -or $PSVersionTable.PSVersion.Major -ne 5 -or
    $PSVersionTable.PSEdition -ne 'Desktop') { throw 'N0_UNSUPPORTED_HOST' }
if (-not [Diagnostics.Stopwatch]::IsHighResolution) { throw 'N0_BLOCKED_CLOCK' }
$frequency=[Diagnostics.Stopwatch]::Frequency
$helperT0=[Diagnostics.Stopwatch]::GetTimestamp()
if ($frequency -le 0 -or $helperT0 -lt 0 -or [decimal]$helperT0+[decimal]$frequency*10 -gt [long]::MaxValue) {
    throw 'N0_BLOCKED_CLOCK'
}
$selfDeadline=[long]([decimal]$helperT0+[decimal]$frequency*10)
$wire=$null
function Get-N0HelperHash([string]$Path) {
    $stream=$null; $sha=$null
    try {
        $stream=[IO.File]::OpenRead($Path); $sha=[Security.Cryptography.SHA256]::Create()
        return ([BitConverter]::ToString($sha.ComputeHash($stream))).Replace('-','').ToLowerInvariant()
    } finally { if ($stream) { $stream.Dispose() }; if ($sha) { $sha.Dispose() } }
}
function Assert-N0HelperPath([string]$Path) {
    if (-not $Path -or $Path -match '[\x00-\x1f\x7f"\r\n]' -or $Path -notmatch '^[a-zA-Z]:\\' -or
        $Path.Substring(2).Contains(':')) { throw 'N0_UNSAFE_PATH' }
    $full=[IO.Path]::GetFullPath($Path)
    if ($full.TrimEnd('\') -cne $Path.TrimEnd('\')) { throw 'N0_NONCANONICAL_PATH' }
    $item=Get-Item -LiteralPath $full -Force
    if (-not $item.PSIsContainer) { throw 'N0_NOT_DIRECTORY' }
    $walk=$item
    while ($walk) {
        if (($walk.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { throw 'N0_REPARSE_PATH' }
        $walk=$walk.Parent
    }
    $drive=New-Object IO.DriveInfo([IO.Path]::GetPathRoot($full))
    if ($drive.DriveType -notin @([IO.DriveType]::Fixed,[IO.DriveType]::Removable,[IO.DriveType]::Ram)) {
        throw 'N0_NONLOCAL_PATH'
    }
    $checkout=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..\..')).TrimEnd('\')
    if ($full.Equals($checkout,[StringComparison]::OrdinalIgnoreCase) -or
        $full.StartsWith($checkout+'\',[StringComparison]::OrdinalIgnoreCase)) { throw 'N0_CHECKOUT_OUTPUT' }
    return $full
}
try {
    $canonical=Assert-N0HelperPath $RunDir
    if ([IO.Path]::GetFileName($canonical.TrimEnd('\')) -cne ('ricon-n0-'+$RunId)) { throw 'N0_DIRECTORY_IDENTITY' }
    $manifestPath=Join-Path $canonical 'manifest.json'
    $manifestFile=Get-Item -LiteralPath $manifestPath -Force
    if (($manifestFile.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0 -or
        $manifestFile.Length -le 0 -or $manifestFile.Length -gt 8192) { throw 'N0_BAD_MANIFEST' }
    $utf8=New-Object Text.UTF8Encoding($false,$true)
    $manifestStream=$null; $manifestBytes=New-Object byte[] 8193; $manifestLength=0
    try {
        $manifestStream=New-Object IO.FileStream($manifestPath,[IO.FileMode]::Open,[IO.FileAccess]::Read,[IO.FileShare]::Read)
        while ($manifestLength -lt 8193) {
            $n=$manifestStream.Read($manifestBytes,$manifestLength,8193-$manifestLength)
            if ($n -eq 0) { break }
            $manifestLength+=$n
        }
        if ($manifestLength -le 0 -or $manifestLength -gt 8192) { throw 'N0_BAD_MANIFEST' }
    } finally { if ($manifestStream) { $manifestStream.Dispose() } }
    $manifestText=$utf8.GetString($manifestBytes,0,$manifestLength)
    $manifest=$manifestText | ConvertFrom-Json
    # Manifest is generated by our fixed runner. Exact property set and canonical reserialization
    # reject duplicate/unknown properties as well as edits to its representation.
    if (($manifest | ConvertTo-Json -Depth 8 -Compress) -cne $manifestText) { throw 'N0_NONCANONICAL_MANIFEST' }
    $expected=@('schema','runId','ownerToken','scenario','inputGit','writingBaseline','runDir',
        'helperScript','executable','executableVersion','host','os','psVersion','clockSource',
        'frequency','highResolution','runnerPid','scripts')
    $actual=@($manifest.PSObject.Properties.Name)
    if ($actual.Count -ne $expected.Count) { throw 'N0_BAD_MANIFEST_FIELDS' }
    foreach ($name in $expected) { if ($actual -cnotcontains $name) { throw 'N0_BAD_MANIFEST_FIELDS' } }
    $fixedExe='C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe'
    $ownScript=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot 'k0-neutral-helper.ps1'))
    if (($manifest.schema -isnot [int] -and $manifest.schema -isnot [long]) -or $manifest.schema -ne 1 -or
        ($manifest.runnerPid -isnot [int] -and $manifest.runnerPid -isnot [long]) -or $manifest.runnerPid -le 0 -or
        $manifest.runId -cne $RunId -or $manifest.ownerToken -cne $OwnerToken -or
        $manifest.scenario -cne $Scenario -or $manifest.runDir -cne $canonical -or
        $manifest.helperScript -cne $ownScript -or $PSCommandPath -cne $ownScript -or
        $manifest.executable -cne $fixedExe -or $manifest.host -cne [Environment]::MachineName -or
        $manifest.os -cne [Environment]::OSVersion.Version.ToString() -or
        $manifest.psVersion -cne $PSVersionTable.PSVersion.ToString() -or
        $manifest.executableVersion -cne [Diagnostics.FileVersionInfo]::GetVersionInfo($fixedExe).FileVersion -or
        $manifest.clockSource -cne 'QPC_STOPWATCH_RAW' -or $manifest.highResolution -isnot [bool] -or
        -not $manifest.highResolution -or $manifest.frequency -isnot [string] -or
        $manifest.frequency -cne $frequency.ToString() -or $manifest.inputGit -cne '2880204' -or
        $manifest.writingBaseline -cne '1e58666') { throw 'N0_MANIFEST_IDENTITY' }
    $names=@('k0-neutral-core.ps1','k0-neutral-helper.ps1','k0-neutral-preflight.ps1','k0-neutral-selftest.ps1')
    if (@($manifest.scripts.PSObject.Properties).Count -ne 4) { throw 'N0_SCRIPT_IDENTITY' }
    foreach ($name in $names) {
        if (@($manifest.scripts.PSObject.Properties.Name) -cnotcontains $name -or
            $manifest.scripts.$name -cne (Get-N0HelperHash (Join-Path $PSScriptRoot $name))) { throw 'N0_SCRIPT_IDENTITY' }
    }
    # Only now may the fixed helper create its sole output file. No core import is necessary.
    $wirePath=Join-Path $canonical 'wire.jsonl'
    $wire=New-Object IO.FileStream($wirePath,[IO.FileMode]::CreateNew,[IO.FileAccess]::Write,[IO.FileShare]::Read)
    $script:wireRecords=0; $script:wireBytes=0
    function Write-N0Wire([string]$Kind,[int]$Sequence,[string]$Emit='') {
        $record=[ordered]@{schema=1;runId=$RunId;ownerToken=$OwnerToken;helperPid=$PID;scenario=$Scenario
            frequency=$frequency.ToString();highResolution=$true;kind=$Kind;seq=$Sequence}
        if ($Kind -ceq 'N0_SAMPLE') { $record.tEmit=$Emit; $record.payload='N0_NEUTRAL' }
        if ($Kind -ceq 'N0_DONE') { $record.sampleCount=8 }
        $bytes=$utf8.GetBytes(($record | ConvertTo-Json -Compress)+"`n")
        if ($bytes.Length -gt 1024 -or $script:wireRecords -ge 16 -or $script:wireBytes+$bytes.Length -gt 16384) {
            throw 'N0_HELPER_QUOTA'
        }
        $wire.Write($bytes,0,$bytes.Length); $wire.Flush($true)
        $script:wireRecords++; $script:wireBytes+=$bytes.Length
    }
    Write-N0Wire 'N0_HELLO' 0
    if ($Scenario -cne 'Hanging') {
        for ($sequence=1; $sequence -le 8; $sequence++) {
            $now=[Diagnostics.Stopwatch]::GetTimestamp()
            if ($now -ge $selfDeadline -or $now -lt $helperT0) { break }
            $emit=$now.ToString([Globalization.CultureInfo]::InvariantCulture)
            if ($Scenario -ceq 'DelayEmit' -and $sequence -eq 1) { [Threading.Thread]::Sleep(600) }
            Write-N0Wire 'N0_SAMPLE' $sequence $emit
            # Spacing is measured from completion, never catch-up after a delayed write.
            if ($sequence -lt 8) { [Threading.Thread]::Sleep(100) }
        }
        if ($sequence -eq 9 -and [Diagnostics.Stopwatch]::GetTimestamp() -lt $selfDeadline) { Write-N0Wire 'N0_DONE' 9 }
    }
    # Normal remains alive after DONE so runner can observe a stop command. Self-cap is best-effort.
    $last=$helperT0
    while ($true) {
        $now=[Diagnostics.Stopwatch]::GetTimestamp()
        if ($now -ge $selfDeadline -or $now -lt $last) { break }
        $last=$now; [Threading.Thread]::Sleep(10)
    }
} finally {
    if ($wire) { $wire.Dispose() }
}
